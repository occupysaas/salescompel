#!/bin/sh
# check-file-size.sh -- fail when a NEW or GROWN source file passes the line limit.
#
#   sh scripts/check-file-size.sh                      # check the working tree
#   sh scripts/check-file-size.sh --base origin/main   # also: the allowlist may only shrink
#   sh scripts/check-file-size.sh --write-allowlist    # rewrite the allowlist (after a split)
#   sh scripts/check-file-size.sh --self-test          # prove the check can still fail
#
# A file is "too big" when it has more than FILESIZE_LIMIT lines (default 500). Files that
# were already too big when the check was adopted are listed in .filesize-allowlist as
# "<max lines> <path>"; each may stay that size or shrink, never grow. With --base, the
# allowlist itself is compared with the base branch: a PR may delete or lower a line, never
# add or raise one. So the only way past the limit is a maintainer-reviewed exception.
#
# Not counted: generated files and anything under vendor/, node_modules/, testdata/ or
# dist/. A file is generated only when one of its first 10 lines is exactly Go's marker
# "// Code generated <by what>. DO NOT EDIT." (also with "#" or "--" instead of "//" for
# Python and SQL), or "// @generated" on a line by itself.
# A comment that merely mentions "auto-generated" exempts nothing.
#
# Settings (environment): FILESIZE_LIMIT (500), FILESIZE_EXTS ("go ts vue py sql"), FILESIZE_ALLOWLIST (.filesize-allowlist, relative to the repo root).
#
# Exit 0 clean, 1 violation, 2 could not judge (not a git repo, bad --base, malformed
# allowlist, no source files found). POSIX sh + awk + git; runs on GitHub's ubuntu runners,
# macOS and Git Bash.

set -u
export MSYS_NO_PATHCONV=1
LIMIT="${FILESIZE_LIMIT:-500}"
EXTS="${FILESIZE_EXTS:-go ts vue py sql}"
ALLOW="${FILESIZE_ALLOWLIST:-.filesize-allowlist}"
SKIP='(^|/)(vendor|node_modules|testdata|dist)/'
BASE=""
MODE=check

die2() { echo "check-file-size: could not judge: $*" >&2; exit 2; }

while [ $# -gt 0 ]; do
  case "$1" in
    --base) [ $# -ge 2 ] || die2 "--base needs a git ref"; BASE="$2"; shift 2 ;;
    --base=*) BASE="${1#--base=}"; shift ;;
    --write-allowlist) MODE=write; shift ;;
    --self-test) MODE=selftest; shift ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) die2 "unknown argument: $1" ;;
  esac
done

case "$LIMIT" in ''|*[!0-9]*) die2 "FILESIZE_LIMIT must be a whole number, got '$LIMIT'" ;; esac

# ---------------------------------------------------------------------------- self-test
if [ "$MODE" = selftest ]; then
  here=$(cd "$(dirname "$0")" && pwd) || die2 "cannot find my own directory"
  me="$here/$(basename "$0")"
  tmp=$(mktemp -d 2>/dev/null || mktemp -d -t fsz) || die2 "mktemp failed"
  trap 'rm -rf "$tmp"' EXIT
  fails=0
  lines() { awk -v n="$2" 'BEGIN { for (i = 1; i <= n; i++) print "// line " i }' > "$1"; }
  expect() {  # expect <code> <label> -- runs the check in $tmp/repo with limit 20
    want="$1"; label="$2"; shift 2
    (cd "$tmp/repo" && FILESIZE_LIMIT=20 FILESIZE_ALLOWLIST=.filesize-allowlist \
      sh "$me" "$@" >"$tmp/out" 2>&1)
    got=$?
    if [ "$got" -eq "$want" ]; then echo "  ok   $label"
    else echo "  FAIL $label (exit $got, want $want)"; sed 's/^/       | /' "$tmp/out"; fails=$((fails + 1)); fi
  }
  mkdir -p "$tmp/repo/vendor/x" "$tmp/repo/pkg" "$tmp/repo/db" "$tmp/notrepo"
  cd "$tmp/repo" || die2 "cannot enter $tmp/repo"
  git init -q . && git config user.email t@example.invalid && git config user.name t \
    && git config commit.gpgsign false && git config core.autocrlf false || die2 "git init failed"
  lines pkg/small.go 10
  lines vendor/x/big.go 40
  { echo "// Code generated by tool. DO NOT EDIT."; awk 'BEGIN { for (i = 0; i < 40; i++) print "// g" }'; } > pkg/gen.go
  : > .filesize-allowlist
  expect 0 "small, vendored and generated files pass"
  lines db/big.sql 30
  expect 1 "a new SQL file over the limit fails"
  { echo "-- Code generated by tool. DO NOT EDIT."; awk 'BEGIN { for (i = 0; i < 30; i++) print "-- g" }'; } > db/big.sql
  expect 0 "a generated SQL file is not counted"
  rm -f db/big.sql
  { echo "// TODO: maybe this should be auto-generated someday"; echo "// @generated by hand"
    echo "x := 1 // Code generated by tool. DO NOT EDIT."
    awk 'BEGIN { for (i = 0; i < 40; i++) print "// h" }'; } > pkg/handwritten.go
  expect 1 "a big file that only MENTIONS generation is still counted"
  grep -q '^TOO BIG  pkg/handwritten.go' "$tmp/out" && ! grep -q 'pkg/gen.go' "$tmp/out"     && echo "  ok   ...it is reported, the real generated file is not"     || { echo "  FAIL wrong report for a fake generated marker"; sed 's/^/       | /' "$tmp/out"; fails=$((fails + 1)); }
  rm -f pkg/handwritten.go
  lines "pkg/big file.go" 25
  expect 1 "a new file over the limit fails (path with a space)"
  grep -q '^TOO BIG  pkg/big file.go: 25 lines' "$tmp/out" && ! grep -q STALE "$tmp/out"     && echo "  ok   ...reported as TOO BIG, nothing STALE"     || { echo "  FAIL wrong report for a new big file"; sed 's/^/       | /' "$tmp/out"; fails=$((fails + 1)); }
  expect 0 "--write-allowlist records it" --write-allowlist
  grep -q '^25 pkg/big file.go$' .filesize-allowlist || { echo "  FAIL allowlist line missing"; fails=$((fails + 1)); }
  expect 0 "an allowlisted file at its recorded size passes"
  lines "pkg/big file.go" 27
  expect 1 "an allowlisted file that grew fails"
  lines "pkg/big file.go" 23
  expect 1 "an allowlisted file that shrank asks for its line to be lowered"
  expect 0 "--write-allowlist lowers it" --write-allowlist
  expect 0 "...and then it passes"
  git add -A && git commit -qm base || die2 "commit failed"
  printf '23 pkg/big file.go\n30 pkg/small.go\n' > .filesize-allowlist
  lines pkg/small.go 30
  expect 0 "without --base an added allowlist line is accepted"
  expect 1 "with --base an ADDED allowlist line fails" --base HEAD
  grep -q '^ADDED    pkg/small.go' "$tmp/out" && ! grep -q 'ADDED    pkg/big' "$tmp/out"     && echo "  ok   ...and only the added line is reported"     || { echo "  FAIL wrong report for an added line"; sed 's/^/       | /' "$tmp/out"; fails=$((fails + 1)); }
  printf '24 pkg/big file.go\n' > .filesize-allowlist
  lines pkg/small.go 10
  lines "pkg/big file.go" 24
  expect 1 "with --base a RAISED allowlist line fails" --base HEAD
  lines "pkg/big file.go" 10
  : > .filesize-allowlist
  expect 0 "with --base a removed line (file split) passes" --base HEAD
  printf '23 pkg/big file.go\n' > .filesize-allowlist
  expect 1 "a stale line for a file now under the limit fails"
  printf 'lots pkg/x.go\n' > .filesize-allowlist
  expect 2 "a malformed allowlist line cannot be judged"
  : > .filesize-allowlist
  expect 2 "an unknown --base ref cannot be judged" --base no-such-ref
  (cd "$tmp/repo" && FILESIZE_EXTS=nothinghere sh "$me" >"$tmp/out" 2>&1); got=$?
  if [ "$got" -eq 2 ]; then echo "  ok   no source files at all cannot be judged"
  else echo "  FAIL no source files at all (exit $got, want 2)"; fails=$((fails + 1)); fi
  (cd "$tmp/notrepo" && GIT_CEILING_DIRECTORIES="$tmp" sh "$me" >"$tmp/out" 2>&1); got=$?
  if [ "$got" -eq 2 ]; then echo "  ok   outside a git repo cannot be judged"
  else echo "  FAIL outside a git repo (exit $got, want 2)"; fails=$((fails + 1)); fi
  if [ "$fails" -eq 0 ]; then echo "check-file-size --self-test: ALL PASS"; exit 0; fi
  echo "check-file-size --self-test: $fails FAILED"; exit 1
fi

# ------------------------------------------------------------------------------ measure
root=$(git rev-parse --show-toplevel 2>/dev/null) || die2 "not inside a git work tree"
cd "$root" || die2 "cannot enter $root"
work=$(mktemp -d 2>/dev/null || mktemp -d -t fsz) || die2 "mktemp failed"
trap 'rm -rf "$work"' EXIT

set --
for e in $EXTS; do set -- "$@" "*.$e"; done
# Tracked plus new untracked (not ignored) files, so a big file is caught before it is committed.
git -c core.quotepath=off ls-files --cached --others --exclude-standard -- "$@" \
  > "$work/files" || die2 "git ls-files failed"

# One awk pass: count lines per file, skip generated/vendored, keep the ones over LIMIT.
awk -v limit="$LIMIT" -v skip="$SKIP" -v countfile="$work/count" '
  {
    path = $0
    if (path ~ skip) next
    n = 0; gen = 0
    while ((r = (getline line < path)) > 0) {
      n++
      if (n <= 10) {
        sub(/\r$/, "", line)
        if (line ~ /^(\/\/|#|--) Code generated .* DO NOT EDIT\.$/ || line ~ /^\/\/ @generated$/) gen = 1
      }
    }
    close(path)
    if (r < 0 && n == 0) next          # listed but deleted from the working tree
    scanned++
    if (!gen && n > limit) print n " " path
  }
  END { print scanned + 0 > countfile }
' "$work/files" | sort -k2 > "$work/big" || die2 "awk failed"
scanned=$(cat "$work/count" 2>/dev/null || echo 0)
[ "$scanned" -gt 0 ] || die2 "no files matched extensions '$EXTS' -- wrong directory or FILESIZE_EXTS?"

if [ "$MODE" = write ]; then
  {
    echo "# Files that were over $LIMIT lines when the size check was adopted: \"<max lines> <path>\"."
    echo "# Each may only shrink. Split a file, then lower or delete its line"
    echo "# (sh scripts/check-file-size.sh --write-allowlist). CI refuses a PR that adds or raises a line."
    cat "$work/big"
  } > "$ALLOW" || die2 "cannot write $ALLOW"
  echo "check-file-size: wrote $(wc -l < "$work/big" | tr -d ' ') entries to $ALLOW (limit $LIMIT, $scanned files scanned)"
  exit 0
fi

# Parse an allowlist into "<max> <path>" lines; exit 2 on a malformed line.
parse_allow() {  # parse_allow <file> <label>
  awk -v label="$2" '
    /^[ \t]*(#|$)/ { next }
    {
      sub(/\r$/, "")
      if (!match($0, /^[0-9]+ /)) { print label ": line " NR " is not \"<max lines> <path>\": " $0 > "/dev/stderr"; bad = 1; next }
      print
    }
    END { exit bad }
  ' "$1"
}

: > "$work/allow"
if [ -f "$ALLOW" ]; then
  parse_allow "$ALLOW" "$ALLOW" > "$work/allow" || die2 "malformed $ALLOW"
fi
echo "check-file-size: limit $LIMIT lines, $scanned files scanned, $(wc -l < "$work/allow" | tr -d ' ') allowlisted ($ALLOW)"

viol=0
# Two inputs: FILENAME tells them apart (FNR==1 counting breaks when the first is empty).
awk -v limit="$LIMIT" -v allowfile="$ALLOW" -v first="$work/allow" '
  {
    n = $1; p = $0; sub(/^[0-9]+ /, "", p)
    if (FILENAME == first) { allow[p] = n + 0; next }
    big[p] = n + 0
    if (!(p in allow)) {
      printf "TOO BIG  %s: %d lines, limit %d. Split it (CONTRIBUTING.md, \"How to split a big file\").\n", p, n, limit
      bad = 1
    } else if (n + 0 > allow[p]) {
      printf "GREW     %s: %d lines, allowlisted at %d. Move the new code to a new file instead.\n", p, n, allow[p]
      bad = 1
    } else if (n + 0 < allow[p]) {
      printf "SHRANK   %s: %d lines, allowlisted at %d. Lower its line in %s to %d (thank you).\n", p, n, allow[p], allowfile, n
      bad = 1
    }
  }
  END {
    for (p in allow) if (!(p in big)) {
      printf "STALE    %s: now under the limit or gone. Delete its line from %s.\n", p, allowfile
      bad = 1
    }
    exit bad
  }
' "$work/allow" "$work/big" || viol=1

if [ -n "$BASE" ]; then
  git rev-parse -q --verify "$BASE^{commit}" >/dev/null || die2 "--base '$BASE' is not a commit (fetch it first)"
  if git cat-file -e "$BASE:$ALLOW" 2>/dev/null; then
    git cat-file -p "$BASE:$ALLOW" > "$work/base_raw" || die2 "cannot read $ALLOW at $BASE"
    parse_allow "$work/base_raw" "$BASE:$ALLOW" > "$work/base" || die2 "malformed $ALLOW at $BASE"
    awk -v allowfile="$ALLOW" -v base="$BASE" -v first="$work/base" '
      {
        n = $1; p = $0; sub(/^[0-9]+ /, "", p)
        if (FILENAME == first) { was[p] = n + 0; next }
        if (!(p in was)) {
          printf "ADDED    %s: new line in %s. The allowlist may only shrink; split the file instead.\n", p, allowfile
          bad = 1
        } else if (n + 0 > was[p]) {
          printf "RAISED   %s: %d in %s, %d on %s. The allowlist may only shrink.\n", p, n, allowfile, was[p], base
          bad = 1
        }
      }
      END { exit bad }
    ' "$work/base" "$work/allow" || viol=1
  else
    echo "check-file-size: $BASE has no $ALLOW -- first adoption, allowlist accepted as the baseline"
  fi
fi

if [ "$viol" -ne 0 ]; then
  echo "check-file-size: FAIL"
  exit 1
fi
echo "check-file-size: ok"
exit 0
